"""Committed input-digest table + ``--verify`` — pin the dataset bytes the benchmark scores.

Adapted from UnderstandingVCS's ``repro/make_hash_tables.py``: the windowed inputs are too large
to commit, so their *digests* are — one entry per (grid, family) with the sidecar manifest's
SHA-256, the channel-list ``feature_hash``, the canonical file name and shape. ``--verify``
re-hashes the sidecars on disk against the committed table (exit-coded), and both modes print
the **SHA-256 of this script itself** so a reviewer can confirm the table was regenerated by
unmodified code. ``evemtbench.integrity`` cross-checks every run record's recorded partition
digests against this table, catching a producer silently swapping data under a fixed version.

    python -m evemtbench.data.input_digests --verify           # re-hash disk vs table
    python -m evemtbench.data.input_digests --write            # regenerate (loop host)
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from .roots import FAMILIES, GRIDS, windows_dir
from .windows import DEFAULT_CONTRACT, find_window_files

TABLE_PATH = Path(__file__).resolve().parent / "input_digests.json"


def load_table() -> dict:
    """The committed digest table ({} when not yet generated)."""
    try:
        return json.loads(TABLE_PATH.read_text())
    except (OSError, json.JSONDecodeError):
        return {}


def _self_hash() -> str:
    return hashlib.sha256(Path(__file__).read_bytes()).hexdigest()


def _digest_one(grid: str, family: str, root=None) -> dict | None:
    """The digest entry for one (grid, family) partition, or None when it has no windows."""
    try:
        files = find_window_files(
            windows_dir(GRIDS[grid], family, root),
            GRIDS[grid].topology,
            contract=DEFAULT_CONTRACT,  # narrow to the benchmark's pinned geometry
        )
    except FileNotFoundError:
        return None
    manifest = json.loads(files["manifest_path"].read_text())
    return {
        "x_file": files["x_path"].name,
        "manifest_sha256": hashlib.sha256(files["manifest_path"].read_bytes()).hexdigest(),
        "feature_hash": manifest.get("feature_hash"),
        "shape": manifest.get("shape"),
    }


def build_table(root=None) -> dict:
    entries: dict[str, dict] = {}
    for grid in sorted(GRIDS):
        for family in sorted(FAMILIES):
            e = _digest_one(grid, family, root)
            if e is not None:
                entries[f"{grid}/{family}"] = e
    return {
        "note": (
            "Digest pins for the windowed benchmark inputs (the bytes are not committed; their "
            "identity is). Regenerate with --write ONLY on a deliberate dataset change; "
            "integrity cross-checks every run record against this table."
        ),
        "generated_by": "python -m evemtbench.data.input_digests --write",
        "entries": entries,
    }


def verify(root=None) -> list[str]:
    """Problems between the committed table and the sidecar manifests on disk."""
    table = load_table().get("entries", {})
    if not table:
        return ["input_digests.json is empty/missing — run --write on the data host first"]
    problems: list[str] = []
    for key, expected in sorted(table.items()):
        grid, family = key.split("/")
        actual = _digest_one(grid, family, root)
        if actual is None:
            problems.append(f"{key}: windows not found on disk (table has an entry)")
            continue
        for field in ("manifest_sha256", "feature_hash", "x_file"):
            if actual[field] != expected[field]:
                problems.append(
                    f"{key}: {field} mismatch — disk {actual[field]!r} != committed "
                    f"{expected[field]!r} (dataset changed under a fixed version?)"
                )
    return problems


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Pin/verify the windowed-input digests.")
    mode = p.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the committed table")
    mode.add_argument("--verify", action="store_true", help="re-hash disk vs the table")
    p.add_argument("--root", default=None, help="data root override")
    args = p.parse_args(argv)

    print(f"input_digests generator sha256: {_self_hash()}")
    if args.write:
        table = build_table(args.root)
        TABLE_PATH.write_text(json.dumps(table, indent=2, sort_keys=True) + "\n")
        print(f"wrote {TABLE_PATH} ({len(table['entries'])} partitions pinned)")
        return 0
    problems = verify(args.root)
    for problem in problems:
        print(f"PROBLEM: {problem}")
    n = len(load_table().get("entries", {}))
    print(f"input digests: {'OK' if not problems else 'FAILED'} — {n} pinned partitions checked")
    return 0 if not problems else 1


if __name__ == "__main__":
    raise SystemExit(main())
