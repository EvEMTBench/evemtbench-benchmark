#!/usr/bin/env python3
"""Completed-runs overview — the report-time UNION across the federated output pools.

EvEMTBench runs on two clusters into two pools ("two pools" in the federation design):
  * the shared HPCVAULT pool  — held_out results from both clusters (TinyGPU + Alex), and
  * the repo-local `outputs/`  — the transfer track (multi_grid_pretrain / transfer_*) plus
    the migrated held_out.
The migrated held_out cells live in BOTH, so a naive per-pool count double-counts them. This script
unions the two pools and DEDUPES by cell, then tabulates completion by protocol x grid x baseline.

This is a COMPLETION view (which result.json exist), the companion to the metric builders
`hpc/make_results.py` (RESULTS.md, held_out) and `evemtbench-leaderboard` (leaderboard.html).
It does NOT read metric values — only presence — so it is fast-ish and login-node safe.

Usage:
  python hpc/completed_overview.py              # plain-text table (terminal)
  python hpc/completed_overview.py --markdown   # -> docs/internal/agent/completed_overview.md
Refreshed hourly + committed by the development repo's overview publisher.

A `result.json` path is <root>/<version>/<task>/<protocol>/<grid>/<baseline>/<test_set>/result.json;
a "cell" = (task, protocol, grid, baseline).
"""

import datetime
import glob
import os
import sys
from collections import defaultdict

VER = os.environ.get("BENCHMARK_VERSION", "0.2.0-dev")
# The shared pool joins the union only when one is configured (SHARED_OUT — e.g. exported by
# hpc/clusters/local.env) and actually differs from the repo-local root (resolved: the repo-local
# `outputs` is a symlink into the shared pool on the reporting machine); otherwise there is
# exactly one pool and a duplicate entry would only double-scan it.
ROOTS = {"repo-local": os.environ.get("OUT", "outputs")}
_SHARED = os.environ.get("SHARED_OUT")
if _SHARED and os.path.realpath(_SHARED) != os.path.realpath(ROOTS["repo-local"]):
    ROOTS["shared"] = _SHARED
BASELINES = ["majority", "threshold", "random_forest", "mlp", "gru", "cnn", "resnet"]


def scan():
    runs_by_root = defaultdict(set)  # root -> {(protocol, grid, baseline, task, test_set)}
    union = set()
    for name, root in ROOTS.items():
        for p in glob.iglob(f"{root}/{VER}/*/*/*/*/*/result.json"):
            parts = p.split("/")
            try:
                i = parts.index(VER)
                task, protocol, grid, baseline, test_set = parts[i + 1 : i + 6]
            except (ValueError, IndexError):
                continue
            key = (protocol, grid, baseline, task, test_set)
            runs_by_root[name].add(key)
            union.add(key)
    return runs_by_root, union


def aggregate():
    runs_by_root, union = scan()
    cells = {(pr, g, b, t) for (pr, g, b, t, _) in union}
    ho = [(pr, g, b, t) for (pr, g, b, t) in cells if pr == "held_out"]
    grids = sorted({g for (_, g, _, _) in ho})
    mat = defaultdict(lambda: defaultdict(int))
    for _pr, g, b, _t in ho:
        mat[g][b] += 1
    others = defaultdict(int)
    for pr, _g, _b, _t in cells:
        if pr != "held_out":
            others[pr] += 1
    return runs_by_root, union, cells, grids, mat, others


def emit_plain():
    runs_by_root, union, cells, grids, mat, others = aggregate()
    print(f"=== COMPLETED RUNS OVERVIEW (version={VER}) ===")
    print(f"union: {len(union)} result.json  ->  {len(cells)} distinct cells")
    for name in ROOTS:
        rc = {(pr, g, b, t) for (pr, g, b, t, _) in runs_by_root[name]}
        print(f"  {name:14s}: {len(runs_by_root[name]):5d} result.json / {len(rc):4d} cells")
    print("\n=== held_out: DONE cells per grid x baseline ===")
    print(f"{'grid':16s}" + "".join(f"{b[:10]:>11s}" for b in BASELINES) + f"{'TOTAL':>8s}")
    for g in grids:
        print(
            f"{g:16s}"
            + "".join(f"{mat[g].get(b, 0):>11d}" for b in BASELINES)
            + f"{sum(mat[g].values()):>8d}"
        )
    print("\n=== transfer track: DONE cells ===")
    for pr in sorted(others):
        print(f"  {pr:26s}: {others[pr]}")


def emit_markdown():
    runs_by_root, union, cells, grids, mat, others = aggregate()
    today = datetime.date.today().isoformat()
    ho_total = sum(sum(mat[g].values()) for g in grids)
    tr_total = sum(others.values())
    per_root = {n: {(pr, g, b, t) for (pr, g, b, t, _) in runs_by_root[n]} for n in ROOTS}
    # cells present in EVERY configured pool (the migrated held_out); 0 when only one pool exists
    shared = len(set.intersection(*per_root.values())) if len(per_root) > 1 else 0
    L = []
    L.append(f"# Completed-runs overview — `{VER}`")
    L.append("")
    L.append(
        "> **Auto-generated by `hpc/completed_overview.py --markdown` (hourly, by the "
        "development repo's overview publisher). Do NOT hand-edit — rerun the script.** "
        "Completion view (which `result.json` exist); union of the configured federated pools "
        "(shared held_out + repo-local transfer/held_out), deduped by cell. Companion to the "
        "metric builders `RESULTS.md` (held_out) and `leaderboard.html`."
    )
    L.append("")
    L.append(
        f"**As of {today}: {len(cells)} distinct cells** ({len(union)} `result.json`) · "
        + " · ".join(f"{n} {len(per_root[n])}" for n in ROOTS)
        + f" ({shared} shared, deduped)."
    )
    L.append("")
    L.append(f"## held_out — {ho_total} cells (done tasks per grid × baseline)")
    L.append("")
    L.append("| grid | " + " | ".join(BASELINES) + " | total |")
    L.append("|---|" + "|".join(["--:"] * (len(BASELINES) + 1)) + "|")
    for g in grids:
        cellvals = " | ".join(str(mat[g].get(b, 0)) for b in BASELINES)
        L.append(f"| **{g}** | {cellvals} | **{sum(mat[g].values())}** |")
    tot = " | ".join(str(sum(mat[g].get(b, 0) for g in grids)) for b in BASELINES)
    L.append(f"| **TOTAL** | {tot} | **{ho_total}** |")
    L.append("")
    L.append(f"## transfer track — {tr_total} cells")
    L.append("")
    L.append("| protocol | done cells |")
    L.append("|---|--:|")
    for pr in sorted(others):
        L.append(f"| `{pr}` | {others[pr]} |")
    L.append("")
    L.append("## Notes")
    L.append("- `threshold` is a detection-only baseline (one task) → 1/grid complete, not a gap.")
    L.append("- The migrated held_out cells live in both pools; the union dedupes them.")
    L.append("- ieee39 held_out is HELD (new `adapt_grid` incoming) → counts frozen/partial.")
    L.append("- Metrics (not just completion) render in `RESULTS.md` / `leaderboard.html`.")
    L.append("")
    print("\n".join(L))


if __name__ == "__main__":
    if "--markdown" in sys.argv[1:]:
        emit_markdown()
    else:
        emit_plain()
