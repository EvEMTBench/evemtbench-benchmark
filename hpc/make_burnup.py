"""Sprint burnup for the sweep — audit/progress.html from coverage_snapshot.json history.

Scrum's burnup chart, built from data the repo already commits: every snapshot commit of
``coverage_snapshot.json`` is one data point (done cells over time, all protocols + the held_out
headline sub-matrix). Reuses the audit chrome from ``hpc/make_audit.py``.

**Deliberately outside the freshness gate**: the page derives from *git history*, which grows
with every snapshot commit — gating it would make it perpetually one tick stale. It is
allowlisted as ungated in ``hpc/check_results_fresh.py`` (``_UNGATED``) and labelled
"informational" on the page itself. Regenerated by the same loops that regenerate the views;
byte-stable for unchanged history (modulo the standard volatile "updated" line).

    PYTHONPATH=src python hpc/make_burnup.py          # git history -> audit/progress.html
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

_REPO = Path(__file__).resolve().parents[1]
for _p in (_REPO / "src", _REPO / "hpc"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from make_audit import _esc, _git_short_sha, _page  # noqa: E402

SNAPSHOT = "coverage_snapshot.json"


def _git(*args: str) -> str:
    return subprocess.check_output(["git", *args], cwd=_REPO, text=True)


def collect_points() -> list[dict]:
    """One point per commit that touched the snapshot: {iso, done, total, ho_done, ho_total}."""
    try:
        log = _git("log", "--reverse", "--format=%H %cI", "--", SNAPSHOT)
    except subprocess.CalledProcessError:
        return []
    points: list[dict] = []
    for line in log.splitlines():
        sha, _, iso = line.partition(" ")
        try:
            snap = json.loads(_git("show", f"{sha}:{SNAPSHOT}"))
        except (subprocess.CalledProcessError, json.JSONDecodeError):
            continue  # commit removed/predates the snapshot
        ho = snap.get("counts_by_protocol", {}).get("held_out", {})
        points.append(
            {
                "iso": iso,
                "sha": sha[:12],
                "done": snap.get("counts", {}).get("done", 0),
                "total": snap.get("counts", {}).get("total", 0),
                "ho_done": ho.get("done", 0),
                "ho_total": ho.get("total", 0),
            }
        )
    return points


def _svg(points: list[dict]) -> str:
    """A dependency-free inline burnup: done cells over time, all-protocols + held_out."""
    w, h, ml, mr, mt, mb = 880, 300, 52, 12, 14, 34
    iw, ih = w - ml - mr, h - mt - mb
    total = max(p["total"] for p in points)
    t0 = points[0]["iso"]
    t1 = points[-1]["iso"]

    # x by point index when all timestamps are equal (single-commit history), else by time.
    import datetime as dt

    times = [dt.datetime.fromisoformat(p["iso"]) for p in points]
    span = (times[-1] - times[0]).total_seconds() or 1.0

    def x(i: int) -> float:
        if len(points) == 1:
            return ml + iw / 2
        return ml + iw * (times[i] - times[0]).total_seconds() / span

    def y(v: float) -> float:
        return mt + ih * (1 - v / total)

    def poly(key: str) -> str:
        return " ".join(f"{x(i):.1f},{y(p[key]):.1f}" for i, p in enumerate(points))

    grid = "".join(
        f'<line x1="{ml}" y1="{y(total * f):.1f}" x2="{w - mr}" y2="{y(total * f):.1f}" '
        f'stroke="#8884" stroke-dasharray="3 3"/>'
        f'<text x="{ml - 6}" y="{y(total * f) + 4:.1f}" text-anchor="end" font-size="11" '
        f'fill="#888">{int(total * f)}</text>'
        for f in (0.25, 0.5, 0.75, 1.0)
    )
    last = points[-1]
    return f"""<svg viewBox="0 0 {w} {h}" role="img" style="max-width:100%;height:auto"
  aria-label="done cells over time">
  {grid}
  <line x1="{ml}" y1="{y(0)}" x2="{w - mr}" y2="{y(0)}" stroke="#888"/>
  <polyline points="{poly("done")}" fill="none" stroke="#1890ff" stroke-width="2.5"/>
  <polyline points="{poly("ho_done")}" fill="none" stroke="#52c41a" stroke-width="2.5"/>
  <circle cx="{x(len(points) - 1):.1f}" cy="{y(last["done"]):.1f}" r="4" fill="#1890ff"/>
  <circle cx="{x(len(points) - 1):.1f}" cy="{y(last["ho_done"]):.1f}" r="4" fill="#52c41a"/>
  <text x="{ml}" y="{h - 8}" font-size="11" fill="#888">{_esc(t0[:16])}</text>
  <text x="{w - mr}" y="{h - 8}" font-size="11" fill="#888" text-anchor="end">{_esc(t1[:16])}</text>
  <text x="{x(len(points) - 1) - 8:.1f}" y="{y(last["done"]) - 8:.1f}" font-size="12"
    fill="#1890ff" text-anchor="end">all: {last["done"]}/{last["total"]}</text>
  <text x="{x(len(points) - 1) - 8:.1f}" y="{y(last["ho_done"]) + 16:.1f}" font-size="12"
    fill="#52c41a" text-anchor="end">held_out: {last["ho_done"]}/{last["ho_total"]}</text>
</svg>"""


def build_progress(points: list[dict], *, generated_at: str | None = None) -> str:
    if points:
        chart = _svg(points)
        rows = "".join(
            f"<tr><td>{_esc(p['iso'][:16])}</td><td><code>{_esc(p['sha'])}</code></td>"
            f"<td>{p['done']}/{p['total']}</td><td>{p['ho_done']}/{p['ho_total']}</td></tr>"
            for p in reversed(points[-20:])
        )
        table = (
            "<h2>Last snapshots</h2><div class=tablewrap><table><thead><tr><th>when</th>"
            "<th>commit</th><th>done (all)</th><th>done (held_out)</th></tr></thead>"
            f"{rows}</table></div>"
        )
    else:
        chart = "<p>No committed coverage_snapshot.json history yet.</p>"
        table = ""
    body = (
        "<div class=note><b>Informational page — not freshness-gated.</b> Every other audit "
        "page is a pure function of <code>outputs/</code> and byte-checked by "
        "<code>hpc/check_results_fresh.py</code>; this one derives from the <i>git history</i> "
        "of <code>coverage_snapshot.json</code> (which grows with every snapshot commit), so it "
        "is rebuilt by the publishing loop but exempted from the byte-compare "
        "(<code>_UNGATED</code>).</div>"
        "<h2>Done cells over time</h2>"
        '<p class=v><span style="color:#1890ff">■</span> all protocols · '
        '<span style="color:#52c41a">■</span> held_out (the headline 580) — one point per '
        "committed snapshot; the sprint-review burnup.</p>"
        f"{chart}{table}"
    )
    return _page("progress.html", "Sweep progress — burnup", body, generated_at=generated_at)


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Build audit/progress.html from snapshot history.")
    ap.add_argument("--out", default="audit/progress.html")
    args = ap.parse_args(argv)
    from datetime import datetime, timezone

    stamp = f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC · git {_git_short_sha()}"
    points = collect_points()
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_progress(points, generated_at=stamp))
    print(f"wrote {out} ({len(points)} snapshot points)")


if __name__ == "__main__":
    main()
