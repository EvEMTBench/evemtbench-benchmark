"""Before-vs-after comparison of the pretrain/transfer results across benchmark versions.

Compares every (task, protocol, grid, baseline, source, test_set) cell of the pretrain/transfer
protocols between two outputs trees — by default the superseded episode-split results
(``outputs/1.0.0``) and the corrected topology-grouped results (``outputs/<BENCHMARK_VERSION>``) —
and emits a machine-readable JSON plus a compact Markdown summary:

* per-cell absolute metric deltas (every aggregate metric both sides carry);
* the largest movers per (function, metric) — FD/FC balanced accuracy, FL MAE first-class;
* validation-selected winner changes (which baseline a val-selected table row would pick),
  when the gitignored ``val/result.json`` re-scores are present on both sides;
* new failures / newly chance-level cells (balanced accuracy within tol of the 1/k floor).

Deterministic and read-only: a pure function of the two outputs trees (no timestamps), so the
report can be regenerated byte-identically from a clean checkout with the trees mounted.

    PYTHONPATH=src python hpc/compare_transfer_versions.py \
        --out-json paper/planning/transfer_v110_comparison.json \
        --out-md paper/planning/transfer_v110_comparison.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from evemtbench.coverage import PRETRAIN_GRID, iter_cells
from evemtbench.version import BENCHMARK_VERSION

PROTOCOLS = ("multi_grid_pretrain", "transfer_zeroshot", "transfer_finetune")
# headline metric per task function (matches the registry's td.metrics[0])
HEADLINE = {
    "fault_detection": ("balanced_accuracy", +1),
    "fault_classification": ("balanced_accuracy", +1),
    "fault_location": ("mae", -1),
    "fault_category": ("balanced_accuracy", +1),
    "fault_phase": ("balanced_accuracy", +1),
    "fault_grounded": ("balanced_accuracy", +1),
}


def _cell_rel(cell) -> str:
    rel = f"{cell.task}/{cell.protocol}/{cell.grid}/{cell.baseline}"
    if cell.source is not None and cell.source != PRETRAIN_GRID:
        rel += f"/pretrain-{cell.source}"
    return rel


def _agg(doc: dict) -> dict[str, float]:
    out = {}
    for metric, entry in (doc.get("aggregate") or {}).items():
        if isinstance(entry, dict) and isinstance(entry.get("mean"), (int, float)):
            out[metric] = float(entry["mean"])
    return out


def _load(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None


def _function(task: str) -> str:
    return task.rsplit("_", 1)[0]


def collect(outputs: Path, old: str, new: str) -> dict:
    cells = []
    for protocol in PROTOCOLS:
        cells += iter_cells(protocols=(protocol,))
    rows = []
    for cell in cells:
        rel = _cell_rel(cell)
        test_sets = ("test",) if cell.protocol == "multi_grid_pretrain" else ("test", "benchmark")
        for ts in test_sets:
            a = _load(outputs / old / rel / ts / "result.json")
            b = _load(outputs / new / rel / ts / "result.json")
            if a is None and b is None:
                continue
            am, bm = _agg(a) if a else {}, _agg(b) if b else {}
            deltas = {m: round(bm[m] - am[m], 6) for m in sorted(set(am) & set(bm))}
            rows.append(
                {
                    "task": cell.task,
                    "function": _function(cell.task),
                    "view": cell.task.rsplit("_", 1)[1],
                    "protocol": cell.protocol,
                    "grid": cell.grid,
                    "baseline": cell.baseline,
                    "source": cell.source
                    or (PRETRAIN_GRID if cell.protocol != "multi_grid_pretrain" else None),
                    "test_set": ts,
                    "old": am or None,
                    "new": bm or None,
                    "delta": deltas or None,
                    "status": ("both" if a and b else ("old_only" if a else "new_only")),
                }
            )
    return {"old_version": old, "new_version": new, "n_rows": len(rows), "rows": rows}


def summarize(doc: dict, top: int = 15) -> str:
    rows = [r for r in doc["rows"] if r["status"] == "both" and r["delta"]]
    lines = [
        f"# Transfer results: v{doc['old_version']} (episode split) vs "
        f"v{doc['new_version']} (topology-grouped split)",
        "",
        f"Compared cells with results on both sides: "
        f"{len(rows)} of {doc['n_rows']} rows "
        f"(old_only: {sum(r['status'] == 'old_only' for r in doc['rows'])}, "
        f"new_only: {sum(r['status'] == 'new_only' for r in doc['rows'])}).",
        "",
    ]
    for fn, (metric, direction) in HEADLINE.items():
        sub = [r for r in rows if r["function"] == fn and metric in (r["delta"] or {})]
        if not sub:
            continue
        sub.sort(key=lambda r: abs(r["delta"][metric]), reverse=True)
        n_better = sum(1 for r in sub if direction * r["delta"][metric] > 0)
        n_worse = sum(1 for r in sub if direction * r["delta"][metric] < 0)
        lines += [
            f"## {fn} — {metric} ({len(sub)} cells; improved {n_better}, degraded {n_worse})",
            "",
            "| task | protocol | grid | baseline | source | set | old | new | Δ |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for r in sub[:top]:
            lines.append(
                f"| {r['task']} | {r['protocol']} | {r['grid']} | {r['baseline']} | "
                f"{r['source'] or '—'} | {r['test_set']} | {r['old'][metric]:.4f} | "
                f"{r['new'][metric]:.4f} | {r['delta'][metric]:+.4f} |"
            )
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--outputs", default="outputs")
    p.add_argument("--old", default="1.0.0")
    p.add_argument("--new", default=BENCHMARK_VERSION)
    p.add_argument("--out-json", default=None)
    p.add_argument("--out-md", default=None)
    args = p.parse_args()

    doc = collect(Path(args.outputs), args.old, args.new)
    if args.out_json:
        Path(args.out_json).write_text(json.dumps(doc, indent=2, sort_keys=True) + "\n")
        print(f"wrote {args.out_json} ({doc['n_rows']} rows)")
    md = summarize(doc)
    if args.out_md:
        Path(args.out_md).write_text(md)
        print(f"wrote {args.out_md}")
    else:
        print(md)


if __name__ == "__main__":
    main()
